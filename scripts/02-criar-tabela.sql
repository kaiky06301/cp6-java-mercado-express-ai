-- Tabela do histórico de conversas (mesma estrutura gerada pelo JPA com ddl-auto=update).
-- Execute conectado ao banco mercado_express_ai:
--   psql -h localhost -p 5434 -U mercado -d mercado_express_ai -f scripts/02-criar-tabela.sql

CREATE TABLE IF NOT EXISTS historico_chat (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pergunta   VARCHAR(1000) NOT NULL,
    resposta   TEXT          NOT NULL,
    data_hora  TIMESTAMP(6)  NOT NULL,
    provedor   VARCHAR(50)   NOT NULL,
    modelo     VARCHAR(100)  NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_historico_chat_data_hora ON historico_chat (data_hora);
